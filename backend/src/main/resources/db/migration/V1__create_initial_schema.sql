CREATE TABLE ingredients (
                             id bigint GENERATED BY DEFAULT AS IDENTITY,
                             name varchar(50) NOT NULL,

                             CONSTRAINT pk_ingredients PRIMARY KEY (id),
                             CONSTRAINT uq_ingredients_name UNIQUE (name)
);

CREATE TABLE recipes (
                         id bigint GENERATED BY DEFAULT AS IDENTITY,
                         name varchar(100) NOT NULL,
                         minutes integer NOT NULL,
                         steps jsonb NOT NULL,

                         CONSTRAINT pk_recipes PRIMARY KEY (id),
                         CONSTRAINT uq_recipes_name UNIQUE (name)
);

CREATE TABLE fridge_ingredients (
                                    id bigint GENERATED BY DEFAULT AS IDENTITY,
                                    ingredient_id bigint NOT NULL,

                                    CONSTRAINT pk_fridge_ingredients PRIMARY KEY (id),
                                    CONSTRAINT uq_fridge_ingredients_ingredient UNIQUE (ingredient_id),
                                    CONSTRAINT fk_fridge_ingredients_ingredient
                                        FOREIGN KEY (ingredient_id)
                                            REFERENCES ingredients (id)
);

CREATE TABLE recipe_ingredients (
                                    id bigint GENERATED BY DEFAULT AS IDENTITY,
                                    recipe_id bigint NOT NULL,
                                    ingredient_id bigint NOT NULL,
                                    quantity numeric(10, 2),
                                    unit varchar(20),

                                    CONSTRAINT pk_recipe_ingredients PRIMARY KEY (id),
                                    CONSTRAINT uq_recipe_ingredients_recipe_ingredient
                                        UNIQUE (recipe_id, ingredient_id),
                                    CONSTRAINT fk_recipe_ingredients_recipe
                                        FOREIGN KEY (recipe_id)
                                            REFERENCES recipes (id),
                                    CONSTRAINT fk_recipe_ingredients_ingredient
                                        FOREIGN KEY (ingredient_id)
                                            REFERENCES ingredients (id)
);